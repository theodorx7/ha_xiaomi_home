"""Structural validator for the generated miio_specs.py file.

The file is generated by scripts/transpile_miio.py and consumed by
miot_lan.py through MIIO_SPECS. A malformed generation (wrong lambda
arity, broken mapping dicts, props missing from profile_models.yaml)
would otherwise only surface as per-property misses at runtime, or as
AttributeError/TypeError inside a single device call. These tests read
the real generated file and check the invariants miot_lan.py relies on:
key format, config field types, callable signatures, dict mappings being
invertible, and the model whitelist matching lan/profile_models.yaml.
"""
# pylint: disable=protected-access
import inspect
from pathlib import Path
from unittest.mock import AsyncMock, patch

import pytest
import yaml

from custom_components.xiaomi_home.miot.common import MIoTHttp
from custom_components.xiaomi_home.miot.miot_error import (
    MIoTErrorCode, MIoTSpecError)
from custom_components.xiaomi_home.miot.miot_lan import MIIO_SPECS
from custom_components.xiaomi_home.miot.miot_spec import MIoTSpecParser
from custom_components.xiaomi_home.miot.miot_storage import MIoTStorage

SPECS_PATH = Path(__file__).parent.parent / (
    'custom_components/xiaomi_home/miot/miio_specs.py')
PROFILE_MODELS_PATH = Path(__file__).parent.parent / (
    'custom_components/xiaomi_home/miot/lan/profile_models.yaml')

VALID_FIELDS = {
    'prop', 'setter', 'dict', 'template', 'set_template', 'format',
    'default'
}


def _all_models():
    return sorted(MIIO_SPECS)


def test_file_exists_and_loads() -> None:
    """The generated file is present and imports into MIIO_SPECS."""
    assert SPECS_PATH.is_file()
    assert MIIO_SPECS, 'MIIO_SPECS must not be empty'


def test_every_model_has_miio_specs() -> None:
    """miot_lan.py reads spec['miio_specs'] on every call: a model entry
    without the key means every property of that model errors out."""
    for model in _all_models():
        assert 'miio_specs' in MIIO_SPECS[model], model
        assert MIIO_SPECS[model]['miio_specs'], f'{model}: empty miio_specs'


@pytest.mark.parametrize('model', _all_models())
def test_prop_keys_have_siid_piid_format(model) -> None:
    """Keys are 'prop.<siid>.<piid>' with positive ints: that is how
    set_prop_async builds the lookup key."""
    for prop_key in MIIO_SPECS[model]['miio_specs']:
        parts = prop_key.split('.')
        assert len(parts) == 3 and parts[0] == 'prop', (model, prop_key)
        assert parts[1].isdigit() and int(parts[1]) > 0, (model, prop_key)
        assert parts[2].isdigit() and int(parts[2]) > 0, (model, prop_key)


@pytest.mark.parametrize('model', _all_models())
def test_prop_configs_have_known_fields_only(model) -> None:
    """A mistyped generator field (e.g. 'seter') would be silently ignored
    by miot_lan.py; restrict the vocabulary."""
    for prop_key, cfg in MIIO_SPECS[model]['miio_specs'].items():
        unknown = set(cfg) - VALID_FIELDS
        assert not unknown, f'{model} {prop_key}: unknown fields {unknown}'


@pytest.mark.parametrize('model', _all_models())
def test_prop_name_and_setter_types(model) -> None:
    """'setter' is a method name string, or the boolean True meaning
    "writable, method name is set_<prop>" (miot_lan.py derives it)."""
    for prop_key, cfg in MIIO_SPECS[model]['miio_specs'].items():
        assert isinstance(cfg.get('prop'), str) and cfg['prop'], (
            model, prop_key)
        setter = cfg.get('setter')
        assert setter is None or setter is True or isinstance(
            setter, str), (model, prop_key)


@pytest.mark.parametrize('model', _all_models())
def test_lambda_signatures_match_call_sites(model) -> None:
    """miot_lan.py calls template(value, props, max_val) for gets and
    set_template(value, props, max_val) for sets: any other arity raises
    TypeError inside a device call."""
    for prop_key, cfg in MIIO_SPECS[model]['miio_specs'].items():
        for field in ('template', 'set_template'):
            fn = cfg.get(field)
            if fn is None:
                continue
            assert callable(fn), f'{model} {prop_key}: {field} not callable'
            params = list(inspect.signature(fn).parameters)
            assert len(params) == 3, (
                f'{model} {prop_key}: {field} takes {params}, expected '
                '(value, props, max_val)')


@pytest.mark.parametrize('model', _all_models())
def test_set_templates_are_callable_on_plausible_values(model) -> None:
    """Call every set_template with (value, props, max_val) the way
    miot_lan.py does; the result must be list, dict-with-method or a
    plain value."""
    for prop_key, cfg in MIIO_SPECS[model]['miio_specs'].items():
        fn = cfg.get('set_template')
        if fn is None:
            continue
        for value, props, max_val in (
                (50, {}, 100), (1, {}, 25), (0, {'natural_level': 1}, 100)):
            try:
                result = fn(value, props, max_val)
            except Exception as err:  # pylint: disable=broad-exception-caught
                raise AssertionError(
                    f'{model} {prop_key}: set_template({value!r}, '
                    f'{props!r}, {max_val}) raised {err}') from err
            assert isinstance(result, (list, dict, int, float)) or result is \
                None, f'{model} {prop_key}: unusable result {result!r}'


@pytest.mark.parametrize('model', _all_models())
def test_dict_mappings_are_invertible(model) -> None:
    """get_prop_async inverts the mapping by value: duplicate values
    collide and the first key silently wins."""
    for prop_key, cfg in MIIO_SPECS[model]['miio_specs'].items():
        mapping = cfg.get('dict')
        if mapping is None:
            continue
        assert isinstance(mapping, dict), (model, prop_key)
        vals = [str(v) for v in mapping.values()]
        assert len(set(vals)) == len(vals), (
            f'{model} {prop_key}: duplicate dict values {mapping}')


def test_error_code_members_exist() -> None:
    """Regression for the enum bug: the two codes the MIIO set-path raises
    exist, are distinct ints in the documented spec range."""
    not_exist = MIoTErrorCode.CODE_INVALID_PROPERTY.value
    not_writable = MIoTErrorCode.CODE_PROPERTY_NOT_WRITABLE.value
    assert isinstance(not_exist, int) and isinstance(not_writable, int)
    assert not_exist != not_writable
    assert -10070 < not_exist < -10060
    assert -10070 < not_writable < -10060


def test_models_match_profile_models_whitelist() -> None:
    """A model in MIIO_SPECS but not in lan/profile_models.yaml means
    miot_lan.py will never add the device to _lan_devices with a model,
    so its MIIO specs are dead weight (or the whitelist is stale).
    Known gap today: yeelink.light.lamp15."""
    profile = yaml.safe_load(PROFILE_MODELS_PATH.read_text(encoding='utf-8'))
    assert profile
    spec_models = set(MIIO_SPECS)
    profile_models = set(profile)
    missing = spec_models - profile_models
    assert missing == {'yeelink.light.lamp15'}, (
        f'MIIO_SPECS models missing from profile_models.yaml: '
        f'{sorted(missing)}')


def test_miio_commands_shape() -> None:
    """The one model with a 'miio_commands' block must keep the shape the
    generator emits (list of {method, params, values})."""
    for model in _all_models():
        commands = MIIO_SPECS[model].get('miio_commands')
        if not commands:
            continue
        assert isinstance(commands, list), model
        for command in commands:
            assert set(command) == {'method', 'params', 'values'}, (
                model, command)
            assert isinstance(command['method'], str), model
            assert isinstance(command['params'], list), model
            assert isinstance(command['values'], bool), model


def test_chunk_properties_is_positive_int() -> None:
    for model in _all_models():
        chunk = MIIO_SPECS[model].get('chunk_properties')
        if chunk is None:
            continue
        assert isinstance(chunk, int) and chunk > 0, (model, chunk)




def test_spec_modify_value_list_descriptions_are_strings() -> None:
    """YAML 1.1 reads bare Off/On/No/Yes as booleans; the spec parser
    calls .strip() on every value-list description, so a boolean
    description crashes the whole device spec parse.
    Unified check across the whole file, not per device."""
    path = (Path(__file__).parent.parent /
            'custom_components/xiaomi_home/miot/specs/spec_modify.yaml')
    data = yaml.safe_load(path.read_text(encoding='utf-8'))
    bad = []
    for urn, cfg in data.items():
        if not isinstance(cfg, dict):
            continue
        for prop_key, prop_cfg in cfg.items():
            if not isinstance(prop_cfg, dict):
                continue
            for item in prop_cfg.get('value-list', []) or []:
                if not isinstance(item.get('description', ''), str):
                    bad.append((urn, prop_key, item))
    assert not bad, f'non-string value-list descriptions: {bad}'


