@pytest.mark.asyncio
async def test_cloud_mode_parse_falls_back_to_the_pure_spec(tmp_path) -> None:
    '''In CLOUD mode the campaign models parse without the fork's spec
    modifications: the entities get the pure catalog spec, whose scale
    matches what the cloud sends.'''

    # pylint: disable=unused-argument
    async def _fake_http(url, params=None):
        if 'instance' in url:
            return FAKE_INSTANCE
        raise MIoTSpecError('offline')

    storage = MIoTStorage(root_path=str(tmp_path))

    async def _parser():
        parser = MIoTSpecParser(lang='en', storage=storage)
        await parser.init_async()
        return parser

    with patch.object(MIoTHttp, 'get_json_async',
                      AsyncMock(side_effect=_fake_http)):
        instance = await (await _parser()).parse(
            urn=URN, skip_cache=True)
        # a mode change clears the shared spec cache, the reload sees
        # the last write only through a fresh parse
        await storage.remove_domain_async(domain='miot_specs')
        pure = await (await _parser()).parse(urn=URN, pure=True)
    mode = instance.services[0].properties[0]
    pure_mode = pure.services[0].properties[0]
    # the regular parse applies the fork's native six-value list
    assert [item.description for item in mode.value_list.items] == [
        'Interval', 'Sleep', 'Low', 'Medium', 'High', 'Auto']
    # the pure parse keeps the catalog three-value list (the cloud scale)
    assert [item.description for item in pure_mode.value_list.items] == [
        'Interval', 'Sleep', 'Auto']
